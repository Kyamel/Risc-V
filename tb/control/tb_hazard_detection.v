`timescale 1ns / 1ps
module tb_hazard_detection;

    // --- DUT inputs ---
    reg [4:0] if_id_rs1_addr; // rs1 of the instruction in ID
    reg [4:0] if_id_rs2_addr; // rs2 of the instruction in ID
    reg [4:0] id_ex_rd_addr;  // rd of the instruction in EX
    reg       id_ex_mem_read; // The instruction in EX is a load

    // --- DUT output ---
    wire      stall;          // Stall generated by the DUT

    // --- Device under test ---
    hazard_detection_unit dut (
        .if_id_rs1(if_id_rs1_addr),
        .if_id_rs2(if_id_rs2_addr),
        .id_ex_rd(id_ex_rd_addr),
        .id_ex_mem_read(id_ex_mem_read),
        .pc_write(),
        .if_id_write(),
        .stall(stall)
    );

    // --- Check task ---
    // Compares the result with the expected value and prints the status.
    task check(string test_name, input expected_stall);
        #1; // Let the combinational logic settle
        if (stall !== expected_stall) begin
            $display("\033[1;31m[FAIL]\033[0m %s: expected stall %b, got %b.", test_name, expected_stall, stall);
        end else begin
            $display("\033[1;32m[PASS]\033[0m %s: stall = %b, as expected.", test_name, stall);
        end
    endtask

    // --- Main test sequence ---
    initial begin
        $display("\n---- HAZARD DETECTION UNIT TEST ----\n");

        // --- Case 1: no hazard (the instruction in EX is not a load) ---
        // EX: add r3, r1, r2  | ID: add r5, r4, r6
        id_ex_mem_read = 0;
        id_ex_rd_addr  = 5'd3;
        if_id_rs1_addr = 5'd4;
        if_id_rs2_addr = 5'd6;
        check("No hazard (not a load)", 1'b0);

        // --- Case 2: no hazard (load without a data dependency) ---
        // EX: lw r3, 0(r1) | ID: add r5, r4, r6
        id_ex_mem_read = 1;
        id_ex_rd_addr  = 5'd3; // EX writes r3
        if_id_rs1_addr = 5'd4; // ID reads r4
        if_id_rs2_addr = 5'd6; // ID reads r6
        check("No hazard (independent load)", 1'b0);

        // --- Case 3: no hazard (load into x0) ---
        // EX: lw x0, 0(r1) | ID: add r5, x0, r6
        // Writing x0 is a NOP, so it must not stall.
        id_ex_mem_read = 1;
        id_ex_rd_addr  = 5'd0; // EX writes x0
        if_id_rs1_addr = 5'd0; // ID reads x0
        if_id_rs2_addr = 5'd6;
        check("No hazard (load into x0)", 1'b0);

        // --- Case 4: hazard on rs1 ---
        // EX: lw r5, 0(r1) | ID: add r6, r5, r2
        id_ex_mem_read = 1;
        id_ex_rd_addr  = 5'd5; // EX writes r5
        if_id_rs1_addr = 5'd5; // ID reads r5
        if_id_rs2_addr = 5'd2;
        check("Hazard (rs1 dependency)", 1'b1);

        // --- Case 5: hazard on rs2 ---
        // EX: lw r5, 0(r1) | ID: add r6, r2, r5
        id_ex_mem_read = 1;
        id_ex_rd_addr  = 5'd5; // EX writes r5
        if_id_rs1_addr = 5'd2;
        if_id_rs2_addr = 5'd5; // ID reads r5
        check("Hazard (rs2 dependency)", 1'b1);

        // --- Case 6: hazard on rs1 and rs2 ---
        // EX: lw r5, 0(r1) | ID: add r6, r5, r5
        id_ex_mem_read = 1;
        id_ex_rd_addr  = 5'd5; // EX writes r5
        if_id_rs1_addr = 5'd5; // ID reads r5
        if_id_rs2_addr = 5'd5; // ID reads r5
        check("Hazard (rs1 and rs2 dependency)", 1'b1);
        
        // --- Case 7: back to no stall ---
        // A load-use hazard cannot be solved by forwarding alone and always needs
        // one stall cycle; this case only checks that the stall goes away.
        id_ex_mem_read = 0;
        check("Back to no stall", 1'b0);


        $display("\n---- FIM DOS TESTES ----\n");
        $finish;
    end

endmodule